create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text not null default '',
  full_name text not null default '',
  avatar_initial text not null default '',
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, full_name, avatar_initial, role)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data ->> 'full_name', split_part(coalesce(new.email, ''), '@', 1)),
    upper(left(coalesce(new.raw_user_meta_data ->> 'full_name', new.email, 'S'), 1)),
    'user'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create table if not exists public.daily_metrics (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  metric_date date not null,
  steps integer not null default 0 check (steps >= 0),
  active_minutes integer not null default 0 check (active_minutes >= 0),
  calories integer not null default 0 check (calories >= 0),
  distance_km numeric(7, 2) not null default 0 check (distance_km >= 0),
  created_at timestamptz not null default now(),
  unique (user_id, metric_date)
);

create table if not exists public.plans (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete cascade,
  plan_date date not null default current_date,
  title text not null,
  detail text not null default '',
  duration_minutes integer not null default 0 check (duration_minutes >= 0),
  intensity text not null default 'ringan',
  status text not null default 'planned' check (status in ('planned', 'done', 'skipped')),
  sort_position integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.workouts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete cascade,
  workout_date date not null default current_date,
  start_time time not null,
  title text not null,
  workout_type text not null default '',
  duration_minutes integer not null default 0 check (duration_minutes >= 0),
  status text not null default 'planned' check (status in ('planned', 'done', 'skipped')),
  sort_position integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.reminders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete cascade,
  title text not null,
  body text not null default '',
  remind_at time not null default '07:00',
  enabled boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.user_settings (
  user_id uuid primary key references public.profiles (id) on delete cascade,
  daily_step_target integer not null default 8000 check (daily_step_target > 0),
  reminder_enabled boolean not null default true,
  reminder_time time not null default '07:00',
  theme text not null default 'light' check (theme in ('light', 'dark', 'system')),
  updated_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

