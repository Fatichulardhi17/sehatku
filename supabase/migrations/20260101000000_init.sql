create or replace view public.admin_user_overview
with (security_invoker = true)
as
select
  p.id,
  p.full_name,
  p.email,
  p.avatar_initial,
  p.role,
  p.created_at,
  coalesce(m.steps, 0) as steps,
  m.metric_date
from public.profiles p
left join lateral (
  select dm.steps, dm.metric_date
  from public.daily_metrics dm
  where dm.user_id = p.id
  order by dm.metric_date desc
  limit 1
) m on true;

